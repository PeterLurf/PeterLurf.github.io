"""Builds the blog and keeps shared parts of every page in sync.

    python build.py

Run it after you add or edit a post, or change templates/side.html. It:
  1. turns each posts/YYYY-MM-DD-slug.md into blog/slug/index.html (using templates/post.html)
  2. writes the full post list into blog/index.html and the three newest into index.html
  3. writes feed.xml so people can subscribe
  4. copies templates/side.html into every page, marking the current section and leaving out
     Blog and Experiments while they're empty; also dates the "Last updated" footers and adds a
     version to the style.css link, so browsers never mix old and new files
  5. writes each page's link-preview tags, icons and canonical URL from its <title> and description
  6. writes sitemap.xml so search engines find every page
  7. writes the homepage's Compute section from compute.json (kept up to date by spend.py)

Needs Python 3 and the markdown package (pip install markdown). Commit the generated files:
GitHub Pages serves them as they are, with no build step on its side.

A post starts with a header like this (highlight and draft are optional):
    ---
    title: My post
    date: 2026-11-02
    summary: One sentence for lists, search results and link previews.
    highlight: true      (yellow highlighter in the lists, for your best posts)
    draft: true          (skipped until you remove this line)
    ---
Math: $inline$ and $$display$$ are rendered with KaTeX. Footnotes: text[^1] then [^1]: note.
"""
import datetime as dt
import hashlib
import html
import json
import re
import shutil
import subprocess
from pathlib import Path

import markdown

SITE = Path(__file__).resolve().parent
URL = "https://peterlurf.github.io"   # used in the feed, the sitemap and link previews
AUTHOR = "Peter Lu"
GENERATED = "<!-- generated by build.py"
SKIP = {"options", "templates"}       # folders that aren't part of the site

# Written into every page's <!-- meta --> block. {title}, {description} and {url} come from the page itself.
# The preview image is the profile photo: square, so the "summary" card (small square image) fits it.
META = """  <link rel="canonical" href="{url}">
  <meta property="og:title" content="{title}">
  <meta property="og:description" content="{description}">
  <meta property="og:type" content="{kind}">
  <meta property="og:url" content="{url}">
  <meta property="og:site_name" content="Peter Lu">
  <meta property="og:image" content="{site}/images/profile.jpg">
  <meta property="og:image:width" content="600">
  <meta property="og:image:height" content="600">
  <meta property="og:image:alt" content="Peter Lu in a propeller hat">
  <meta name="twitter:card" content="summary">
  <link rel="icon" href="data:image/svg+xml,<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'><rect width='32' height='32' rx='7' fill='%231d1da8'/><path d='M12 24V8h5.5a4.75 4.75 0 0 1 0 9.5H12' fill='none' stroke='white' stroke-width='3.4' stroke-linecap='round' stroke-linejoin='round'/></svg>">
  <link rel="apple-touch-icon" href="/images/apple-touch-icon.png">"""

KATEX = """  <link rel="stylesheet" href="https://cdnjs.cloudflare.com/ajax/libs/KaTeX/0.16.9/katex.min.css">
  <script defer src="https://cdnjs.cloudflare.com/ajax/libs/KaTeX/0.16.9/katex.min.js"></script>
  <script defer src="https://cdnjs.cloudflare.com/ajax/libs/KaTeX/0.16.9/contrib/auto-render.min.js"
    onload="renderMathInElement(document.querySelector('.prose'), {delimiters: [{left: '$$', right: '$$', display: true}, {left: '$', right: '$', display: false}]})"></script>
"""

MATH = re.compile(r"\$\$(.+?)\$\$|(?<![\\$\w])\$(?=\S)([^$\n]+?)(?<=\S)\$(?![\w$])", re.S)


def read_post(path):
    m = re.match(r"(\d{4}-\d{2}-\d{2})-(.+)\.md$", path.name)
    if not m:
        raise SystemExit(f"{path.name}: post files are named YYYY-MM-DD-slug.md")
    text = path.read_text(encoding="utf-8")
    head, body = {}, text
    if text.startswith("---"):
        _, front, body = text.split("---", 2)
        for line in front.strip().splitlines():
            k, _, v = line.partition(":")
            head[k.strip()] = v.strip()
    date = dt.date.fromisoformat(head.get("date", m.group(1)))
    for k in ("title", "summary"):   # curly apostrophes, to match the body (markdown's smarty does those)
        if k in head:
            head[k] = re.sub(r"(\w)'", "\\1\u2019", head[k])
    return {
        "slug": m.group(2),
        "source": f"posts/{path.name}",
        "title": head.get("title") or m.group(2).replace("-", " ").capitalize(),
        "summary": head.get("summary", ""),
        "date": date,
        "highlight": head.get("highlight", "").lower() == "true",
        "draft": head.get("draft", "").lower() == "true",
        "body": body,
    }


def render(body):
    # Pull math out first so markdown can't turn x_i_j into emphasis, then put it back.
    stash = []

    def keep(m):
        stash.append(m.group(0))
        return f"@@MATH{len(stash) - 1}@@"

    has_math = bool(MATH.search(body))
    out = markdown.markdown(MATH.sub(keep, body), extensions=["fenced_code", "footnotes", "tables", "smarty"],
                            extension_configs={"footnotes": {"BACKLINK_TEXT": "back"}})
    out = re.sub(r"@@MATH(\d+)@@", lambda m: html.escape(stash[int(m.group(1))], quote=False), out)
    return out, has_math


def fmt(d):
    return f"{d.day} {d:%B %Y}"


def fill(page, marker, content, indent="    "):
    start, end = f"<!-- {marker} -->", f"<!-- /{marker} -->"
    if start not in page or end not in page:
        return page
    before, rest = page.split(start, 1)
    _, after = rest.split(end, 1)
    return f"{before}{start}\n{content}\n{indent}{end}{after}"


def page_url(rel):
    """blog/x/index.html -> https://.../blog/x/"""
    path = "/".join(rel[:-1]) + "/" if rel[-1] == "index.html" else "/".join(rel)
    return URL + "/" + path.lstrip("/")


def changed(f):
    """When a page last changed: its last commit if the site is in git, otherwise the file's own date.
    (On GitHub every file is freshly checked out, so file dates there would all say today.)"""
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%cs", "--", f.name], cwd=f.parent,
                             capture_output=True, text=True).stdout.strip()
        if out:
            return out
    except OSError:   # git isn't installed
        pass
    return dt.date.fromtimestamp(f.stat().st_mtime).isoformat()


def meta(page, rel):
    title = re.search(r"<title>(.*?)</title>", page, re.S).group(1).strip()
    title = re.sub(r"\s*·\s*Peter Lu$", "", title)
    desc = re.search(r'<meta name="description" content="([^"]*)"', page)
    url = page_url(rel)
    block = META.format(url=url, title=title, description=desc.group(1) if desc else "", site=URL,
                        kind="article" if rel[0] == "blog" and len(rel) == 3 else "website")
    if rel == ("404.html",):   # served at every missing URL, so it has no address of its own
        block = "\n".join(l for l in block.splitlines() if "canonical" not in l and "og:url" not in l)
    return block


def post_li(p, dated):
    title = f"<mark>{html.escape(p['title'])}</mark>" if p["highlight"] else html.escape(p["title"])
    link = f'<a class="t" href="/blog/{p["slug"]}/">{title}</a>'
    if dated:
        return (f'      <li><time datetime="{p["date"].isoformat()}">{fmt(p["date"])}</time>'
                f'<div>{link}<span class="s">{html.escape(p["summary"])}</span></div></li>')
    return f'      <li>{link}<span class="v">{fmt(p["date"])}</span></li>'


def compute_section():
    """The homepage's Compute section, from the totals spend.py writes to compute.json. Left out until there are any."""
    f = SITE / "compute.json"
    data = json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}
    spent = sorted(((k, v) for k, v in data.get("providers", {}).items() if v > 0), key=lambda kv: -kv[1])
    if not spent:
        return ""
    rows = "\n".join(f"      <li><span>{html.escape(k)}</span><span>${v:,.0f}</span></li>" for k, v in spent)
    updated = f"; last updated {fmt(dt.date.fromisoformat(data['updated']))}" if data.get("updated") else ""
    return (f'    <h2 id="compute">Compute</h2>\n'
            f'    <p>I pay for my research compute out of my own pocket. So far that\'s '
            f'<strong>${sum(v for _, v in spent):,.0f}</strong>:</p>\n'
            f'    <ul class="bill">\n{rows}\n    </ul>\n'
            f'    <p class="fine">Pulled from each provider\'s billing API every day{updated}.</p>\n')


def main():
    posts = [read_post(f) for f in sorted((SITE / "posts").glob("*.md"))]
    posts = sorted((p for p in posts if not p["draft"]), key=lambda p: p["date"], reverse=True)
    template = (SITE / "templates" / "post.html").read_text(encoding="utf-8")

    # 1. one page per post; remove pages whose post was deleted or renamed
    blog = SITE / "blog"
    keep = {p["slug"] for p in posts}
    for d in blog.iterdir():
        f = d / "index.html"
        if d.is_dir() and d.name not in keep and f.exists() and GENERATED in f.read_text(encoding="utf-8")[:200]:
            shutil.rmtree(d)
    for p in posts:
        content, has_math = render(p["body"])
        page = template
        for k, v in {"title": html.escape(p["title"]), "summary": html.escape(p["summary"]), "source": p["source"],
                     "iso": p["date"].isoformat(), "date": fmt(p["date"]), "math": KATEX if has_math else "",
                     "content": content}.items():
            page = page.replace("{{" + k + "}}", v)
        (blog / p["slug"]).mkdir(exist_ok=True)
        (blog / p["slug"] / "index.html").write_text(page, encoding="utf-8")

    # 2. lists
    full = "\n".join(post_li(p, True) for p in posts)
    latest = "\n".join(post_li(p, False) for p in posts[:3])
    empty = '    <p class="note">Nothing here yet.</p>'
    lists = {"posts": f'    <ul class="posts">\n{full}\n    </ul>' if posts else empty,
             # the homepage's whole Writing section, left out until there's a post
             "latest": f'    <h2 id="writing">Writing</h2>\n    <ul class="list">\n{latest}\n    </ul>\n'
                       f'    <p class="more"><a href="/blog/">All posts</a></p>' if posts else "",
             "compute": compute_section()}

    # 3. feed
    entries = "".join(
        f"""  <entry>
    <title>{html.escape(p['title'])}</title>
    <link href="{URL}/blog/{p['slug']}/"/>
    <id>{URL}/blog/{p['slug']}/</id>
    <updated>{p['date'].isoformat()}T00:00:00Z</updated>
    <summary>{html.escape(p['summary'])}</summary>
  </entry>
""" for p in posts)
    updated = posts[0]["date"].isoformat() if posts else dt.date.today().isoformat()
    (SITE / "feed.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom">
  <title>{AUTHOR}</title>
  <link href="{URL}/"/>
  <link rel="self" href="{URL}/feed.xml"/>
  <id>{URL}/</id>
  <updated>{updated}T00:00:00Z</updated>
  <author><name>{AUTHOR}</name></author>
{entries}</feed>
""", encoding="utf-8")

    # 4 and 5. shared sidebar, lists, head tags, footer date and file versions in every page
    side = (SITE / "templates" / "side.html").read_text(encoding="utf-8").strip()
    # Blog and Experiments appear in the nav only once they have something in them.
    exps = [d for d in (SITE / "experiments").iterdir() if (d / "index.html").exists()]
    empty = {"blog": not posts, "experiments": not exps}
    for name, gone in empty.items():
        if gone:
            side = re.sub(rf'\n *<a href="/{name}/">[^<]*</a>', "", side)
    if all(empty.values()):   # only Home would be left, and the photo already links home
        side = re.sub(r'\n *<nav class="site-nav".*?</nav>', "", side, flags=re.S)
    month = f"{dt.date.today():%B %Y}"
    # A version that changes whenever the file does: after an update, a browser that kept
    # yesterday's page also keeps yesterday's CSS, instead of mixing old HTML with new CSS.
    versions = {name: hashlib.sha1((SITE / name).read_bytes()).hexdigest()[:8] for name in ("style.css",)}
    # Real pages only: skips one-line files like Google's verification file (google….html).
    pages = sorted(f for f in SITE.rglob("*.html") if not (SKIP & set(f.relative_to(SITE).parts))
                   and f.read_text(encoding="utf-8").lstrip().lower().startswith("<!doctype"))
    for f in pages:
        rel = f.relative_to(SITE).parts
        section = "/" + rel[0] + "/" if len(rel) > 1 else "/"
        current = "page" if len(rel) <= 2 else "true"   # a post is inside Blog, not the Blog page itself
        here = side if rel == ("404.html",) else side.replace(f'<a href="{section}">', f'<a href="{section}" aria-current="{current}">')
        page = f.read_text(encoding="utf-8")
        new = fill(page, "side", "  " + here, "  ")
        new = fill(new, "meta", meta(new, rel), "  ")
        for marker, content in lists.items():
            new = fill(new, marker, content)
        new = re.sub(r"<footer>Last updated [A-Z][a-z]+ \d{4}</footer>", f"<footer>Last updated {month}</footer>", new)
        for name, v in versions.items():
            new = re.sub(rf'"/{re.escape(name)}(\?v=\w+)?"', f'"/{name}?v={v}"', new)
        if new != page:
            f.write_text(new, encoding="utf-8")

    # 6. sitemap: every page except the 404 and empty sections, dated by its post or by when it last changed
    dates = {("blog", p["slug"], "index.html"): p["date"] for p in posts}
    listed = [f for f in pages if (rel := f.relative_to(SITE).parts) != ("404.html",) and not empty.get(rel[0])]
    urls = "".join(
        f"  <url><loc>{page_url(rel)}</loc><lastmod>{dates.get(rel) or changed(f)}</lastmod></url>\n"
        for f in listed if (rel := f.relative_to(SITE).parts))
    (SITE / "sitemap.xml").write_text('<?xml version="1.0" encoding="utf-8"?>\n'
                                      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                                      f"{urls}</urlset>\n", encoding="utf-8")

    hidden = [k for k, gone in empty.items() if gone]
    print(f"{len(posts)} post(s) built; {len(pages)} page(s) synced; sitemap lists {len(listed)}"
          + (f"; left out of the nav while empty: {', '.join(hidden)}" if hidden else ""))


if __name__ == "__main__":
    main()
